// What the crafting stations make and from what (Плавильная установка, Ткацкий станок, Элениумный преобразователь):
// the wiki's {{Станок}} table on every page of «Категория:Станки» → data/base-stations.js.
// A station without that table (Расщепитель материи splits gear into elum) is skipped.
// Usage: node tools/update-stations-wiki.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const API = 'https://royalquest.info/api.php';
const get = async params => {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(`${API}?${new URLSearchParams({ format: 'json', ...params })}`, { headers: { 'User-Agent': 'rq-tools station recipes' } });
      return await res.json();
    } catch (e) { if (attempt >= 3) throw e; }
  }
};

const cat = await get({ action: 'query', list: 'categorymembers', cmtitle: 'Категория:Станки', cmlimit: '100' });
const stations = [];
for (const { title } of cat.query.categorymembers) {
  const page = await get({ action: 'parse', page: title, prop: 'wikitext' });
  const text = page.parse?.wikitext?.['*'] || '';
  const m = text.match(/\{\{\s*Станок([\s\S]*?)\}\}/);
  if (!m) { console.log(`${title}: no {{Станок}} table, skipped`); continue; }
  // «|Ресурс1=… |Цена1=… |Компонент11=… |Штук11=…» (one per line or all on one line)
  const p = {};
  for (const [, k, v] of m[1].matchAll(/\|\s*([^=|]+?)\s*=\s*([^|]*)/g)) p[k] = v.trim();
  const items = [];
  for (let i = 1; p[`Ресурс${i}`]; i++) {
    const res = [];
    for (let j = 1; p[`Компонент${i}${j}`]; j++) res.push({ n: p[`Компонент${i}${j}`], c: +p[`Штук${i}${j}`] || 1 });
    items.push({ n: p[`Ресурс${i}`], price: p[`Цена${i}`] || '', res });
  }
  stations.push({ name: title, items });
  console.log(`${title}: ${items.length}`);
}

const out = path.join(root, 'data', 'base-stations.js');
fs.writeFileSync(out, '// Generated by tools/update-stations-wiki.mjs from the Royal Quest Wiki — don\'t edit by hand.\n'
  + '// Crafting stations: items[] = { n: what it makes (1 piece), price: fee per piece ("2592" gold or "30 АР"), res: [{ n, c }] }\n'
  + `(function (d) { if (typeof module === 'object' && module.exports) module.exports = d; else window.RQ_BASE_STATIONS = d; })(${JSON.stringify(stations)});\n`);
console.log('→', path.relative(root, out));
