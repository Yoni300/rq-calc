// The «База» items that are not gear: food, drinks, potions, elixirs, consumables, containers and chests (with their
// contents), trophies, quest items, pets, mounts, helpers, currencies… — facts from the Royal Quest Wiki templates
// ({{Расходник}}, {{Контейнер}}, {{Сундук}}, {{Трофей}}, {{КвестовыйПредмет}}, {{Питомец}}, {{Маунт}}, …) → data/base-goods.js.
// Flavour text (Описание, Пояснение, comments) is NOT copied — only types, prices, effects, durations, contents, who gives.
// Usage: node tools/update-goods-wiki.mjs [--refresh]   (else source/wiki-goods.json)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { categoryPages, templateFields } from './wiki-fetch.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cache = path.join(root, 'source', 'wiki-goods.json');
export const GOODS_CATS = ['Еда', 'Напитки', 'Зелья', 'Эликсиры', 'Аптечки', 'Расходники', 'Прочие расходники', 'Контейнеры', 'Сундуки', 'Подарки',
  'Драгоценные камни', 'Квестовые предметы', 'Особенные предметы', 'Питомец', 'Ездовое животное', 'Помощники', 'Боевой зверь', 'Прикормки', 'Удочки',
  'Фрагменты предметов', 'Улучшение предметов', 'Квестовые ресурсы', 'Трофеи', 'Валюта', 'Бочки', 'Преобразцы', 'Благословения', 'Формы игрока'];
const pages = !process.argv.includes('--refresh') && fs.existsSync(cache) ? JSON.parse(fs.readFileSync(cache, 'utf8')) : await categoryPages(...GOODS_CATS);
if (process.argv.includes('--refresh') || !fs.existsSync(cache)) fs.writeFileSync(cache, JSON.stringify(pages));

// gear the calculator's database doesn't have (event hats and glasses, old and unique pieces): shown as items too,
// so event pages and «Где взять» can open them. Gear the calculator knows stays in «Снаряжение».
const gearCache = path.join(root, 'source', 'wiki-gear.json');
const gearPages = !process.argv.includes('--refresh') && fs.existsSync(gearCache) ? JSON.parse(fs.readFileSync(gearCache, 'utf8')) : await categoryPages('Экипировка', 'Оружие');
if (process.argv.includes('--refresh') || !fs.existsSync(gearCache)) fs.writeFileSync(gearCache, JSON.stringify(gearPages));
{
  const { createRequire } = await import('node:module');
  const RQ = createRequire(import.meta.url)(path.join(root, 'data', 'rqdata.js'));
  const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/\s*\(класс [a-zа-я]\)$/i, '').replace(/\s+/g, ' ').trim();
  const known = new Set(RQ.Equipment.map((e) => norm(e.Name)));
  let added = 0;
  for (const p of gearPages) {
    if (known.has(norm(p.title)) || !/\{\{\s*(Экипировка|Оружие)/.test(p.text)) continue;
    pages.push({ ...p, cat: 'Экипировка' });
    added++;
  }
  console.log('gear not in the calculator:', added, 'of', gearPages.length);
}

const PROSE = /^(Описание|Пояснение|Комментарий|ДопКомментарий|Замечание|История|Цитата|Текст|Изображение\d*|Подпись\d*|Имя)$/;
const LISTS = { 'Дроп': 'Штук', 'ДопДроп': 'ДопШтук', 'Подарок': 'Шт', 'Бонус': null, 'Префикс': null, 'Выдаёт': null, 'Ивент': null, 'Создание': null, 'Особенность': null,
  'Лока': null, 'Получается': null, 'Требуется': null, 'Монстр': null };
const num = (v) => { const x = parseInt(String(v || '').replace(/[\s  ]/g, ''), 10); return Number.isFinite(x) ? x : null; };

const goods = [];
const seen = new Set();
for (const p of pages) {
  if (seen.has(p.title)) continue;
  const tpl = (p.text.match(/\{\{([^|\n}#]+)/) || [])[1]?.trim();
  if (!tpl || !/^[А-ЯЁA-Z]/i.test(tpl) || tpl === 'НПС' || tpl.startsWith('Ячейка') || tpl.startsWith('Изображение')) continue;
  const f = templateFields(p.text, tpl);
  if (!f) continue;
  seen.add(p.title);
  const g = { name: p.title.replace(/\s*\(предмет\)$/, ''), cat: p.cat, tpl, f: {}, lists: {} };
  for (const [k, v] of Object.entries(f)) {
    if (!v || PROSE.test(k)) continue;
    const m = k.match(/^(\D+?)(\d+)$/);
    if (m && m[1] in LISTS) continue; // numbered lists below
    if (/^(Штук|ДопШтук|Шт|Тип)\d+$/.test(k)) continue;
    g.f[k] = v;
  }
  for (const [key, countKey] of Object.entries(LISTS)) {
    const out = [];
    const single = f[key];
    if (single && !['Ивент', 'Выдаёт', 'Монстр'].includes(key)) out.push({ n: single });
    for (let i = 1; i <= 120; i++) {
      const v = f[key + i];
      if (!v) continue;
      out.push(countKey ? { n: v, c: num(f[countKey + i]) || undefined } : { n: v });
    }
    if (out.length) g.lists[key] = out;
  }
  if (f['Выдаёт']) (g.lists['Выдаёт'] ||= []).unshift({ n: f['Выдаёт'] });
  if (!Object.keys(g.f).length) delete g.f;
  if (!Object.keys(g.lists).length) delete g.lists;
  goods.push(g);
}
goods.sort((a, b) => a.name.localeCompare(b.name, 'ru'));
const out = path.join(root, 'data', 'base-goods.js');
fs.writeFileSync(out, '// Generated by tools/update-goods-wiki.mjs from the Royal Quest Wiki templates — facts only, don\'t edit.\n'
  + '(function (d) { if (typeof module === \'object\' && module.exports) module.exports = d; else window.RQ_BASE_GOODS = d; })(' + JSON.stringify(goods) + ');\n');
const byTpl = {}; for (const g of goods) byTpl[g.tpl] = (byTpl[g.tpl] || 0) + 1;
console.log(`${goods.length} items → data/base-goods.js (${(fs.statSync(out).size / 1024).toFixed(0)} KB)`, JSON.stringify(byTpl));
