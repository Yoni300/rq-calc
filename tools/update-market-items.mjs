// Market item catalog from the Royal Quest Wiki: cards, trophies (incl. ores, gems, crafting materials),
// consumables and upgrade items → data/market-items.js + icons in data/market-img/.
// The market scanner matches recognized names against this list; the site shows names and icons from it.
// Usage: node tools/update-market-items.mjs [--offline]   (--offline reuses source/wiki-market.json, skips icon downloads)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const API = 'https://royalquest.info/api.php';
const cacheFile = path.join(root, 'source', 'wiki-market.json');
const imgDir = path.join(root, 'data', 'market-img');
const outFile = path.join(root, 'data', 'market-items.js');
const offline = process.argv.includes('--offline');
// wiki category → market category; the first listed wins when a page is in several
const CATEGORIES = [['Улучшение предметов', 'upgrade'], ['Карты', 'card'], ['Расходники', 'consumable'], ['Трофеи', 'trophy']];

const get = async params => {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(`${API}?${new URLSearchParams({ format: 'json', ...params })}`, { headers: { 'User-Agent': 'rq-tools market catalog' } });
      return await res.json();
    } catch (e) { if (attempt >= 3) throw e; }
  }
};

async function download() {
  const pages = new Map();
  for (const [cat, key] of CATEGORIES) {
    let cont = {};
    for (let i = 0; i < 40; i++) {
      const j = await get({ action: 'query', generator: 'categorymembers', gcmtitle: 'Категория:' + cat, gcmtype: 'page', gcmlimit: '50',
        prop: 'revisions', rvprop: 'content', rvslots: 'main', ...cont });
      for (const p of Object.values(j.query?.pages || {})) {
        if (!pages.has(p.title)) pages.set(p.title, { title: p.title, pageid: p.pageid, cat: key, text: p.revisions?.[0]?.slots?.main?.['*'] || '' });
      }
      if (!j.continue) break;
      cont = j.continue;
    }
    console.log(cat, '→', [...pages.values()].filter(p => p.cat === key).length);
  }
  // icon URLs: "Файл:<title>.png"
  const list = [...pages.values()];
  for (let i = 0; i < list.length; i += 50) {
    const chunk = list.slice(i, i + 50);
    const j = await get({ action: 'query', prop: 'imageinfo', iiprop: 'url', titles: chunk.map(p => `Файл:${p.title}.png`).join('|') });
    const norm = new Map((j.query?.normalized || []).map(n => [n.to, n.from]));
    for (const f of Object.values(j.query?.pages || {})) {
      const asked = norm.get(f.title) || f.title;
      const p = chunk.find(x => `Файл:${x.title}.png` === asked);
      if (p && f.imageinfo?.[0]?.url) p.icon = f.imageinfo[0].url;
    }
  }
  fs.writeFileSync(cacheFile, JSON.stringify(list));
  return list;
}

const list = offline ? JSON.parse(fs.readFileSync(cacheFile, 'utf8')) : await download();

const field = (text, name) => { const m = text.match(new RegExp(`\\|\\s*${name}\\s*=([^|}\\n]*)`)); return m ? m[1].trim() : null; };
const items = [];
fs.mkdirSync(imgDir, { recursive: true });
const missingIcons = [];
for (const p of list.sort((a, b) => a.title.localeCompare(b.title, 'ru'))) {
  if (/^Категория:|^Шаблон:/.test(p.title)) continue;
  const id = p.pageid; // stable across updates (prices and icons are keyed by it)
  const item = { id, name: field(p.text, 'Имя') || p.title, wiki: p.title, cat: p.cat };
  const type = field(p.text, 'Тип'); if (type) item.type = type;
  const price = parseInt(field(p.text, 'Цена'), 10); if (price > 0) item.npc = price; // what a vendor pays
  const event = field(p.text, 'Ивент'); if (event) item.event = event;
  if (p.icon) {
    const file = path.join(imgDir, id + '.png');
    if (!offline && !fs.existsSync(file)) {
      try { const r = await fetch(p.icon, { headers: { 'User-Agent': 'rq-tools market catalog' } }); if (r.ok) fs.writeFileSync(file, Buffer.from(await r.arrayBuffer())); } catch { /* retry next run */ }
    }
    if (fs.existsSync(file)) item.icon = 1;
  }
  if (!item.icon) missingIcons.push(p.title);
  items.push(item);
}
fs.writeFileSync(outFile, `// Generated by tools/update-market-items.mjs from the Royal Quest Wiki — don't edit by hand.\n`
  + `// cat: card | trophy | consumable | upgrade; npc: vendor price; icon: data/market-img/<id>.png\n`
  + `window.RQ_MARKET_ITEMS = ${JSON.stringify(items)};\n`);
const by = items.reduce((m, i) => (m[i.cat] = (m[i.cat] || 0) + 1, m), {});
console.log('items:', items.length, by, 'without icon:', missingIcons.length, missingIcons.slice(0, 10).join(', '));
