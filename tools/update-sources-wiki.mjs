// «Где взять» for the «База», straight from the wiki's semantic data: who drops an item (Выпадает), which containers
// hold it (Содержит, Подарок), who sells it (Продаёт), which quest or achievement gives it (Награда), which recipe makes
// it (Результат), where it is fished (Улов). → data/base-sources.js: { item: [[source, how, kind], …] }
// how: d drop · b box · g gift · s sells · q reward · r recipe · f catch; kind: m monster · c container · n NPC/shop ·
// q quest · a achievement · r recipe · f fishing spot · x gathering/ore · k collection (the item is NEEDED there) ·
// e event · i game edition · p seasonal adventure · z card page (ignored) · o other.   Usage: node tools/update-sources-wiki.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { api } from './wiki-fetch.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PROPS = { 'Выпадает': 'd', 'Содержит': 'b', 'Подарок': 'g', 'Продаёт': 's', 'Награда': 'q', 'Результат': 'r', 'Улов': 'f' };
const KIND = [[/^Коллекции$/, 'k'], [/^(Рудные месторождения|Ресурсы|Рыбные угодья)$/, 'x'], [/^Игровые события$/, 'e'], [/^Издания игры$/, 'i'],
  [/^Сезонные приключения$/, 'p'], [/^Карты/, 'z'], [/^Монстры$/, 'm'], [/^(Контейнеры|Сундуки|Подарки|Бочки)$/, 'c'], [/НПС|Торговцы/, 'n'], [/^(Задания|Цепочки заданий)$/, 'q'],
  [/^Достижения/, 'a'], [/Рецепты/, 'r'], [/^Рыбные угодья$/, 'f']];
const kindOf = (cats) => { for (const [re, k] of KIND) if (cats.some((c) => re.test(c))) return k; return 'o'; };

// more relations: w — made on a station (station → item); u — a station consumes it (station → component, a USE);
// q — a quest hands it out (Выдаётся). Inverse ones are stored on the item page itself (item → value):
// c — made from (Создаётся, ПолучаетсяИз: item → component; the component also gets v «made into»), t — starting gear (item → class).
Object.assign(PROPS, { 'СоздаётсяНаСтанке': 'w', 'КомпонентНаСтанке': 'u', 'Выдаётся': 'q' });
const INVERSE = { 'Создаётся': 'c', 'ПолучаетсяИз': 'c', 'НачальнаяЭкипировка': 't' };

const out = {};
let total = 0;
const put = (item, rec) => { const list = (out[item] ||= []); if (list.some((x) => x[0] === rec[0] && x[1] === rec[1])) return 0; list.push(rec); return 1; };
async function each(prop, fn) {
  let offset = 0;
  for (let i = 0; i < 200; i++) {
    const j = await api({ action: 'ask', query: `[[${prop}::+]]|?${prop}|?Категория|limit=500|offset=${offset}` });
    for (const [page, r] of Object.entries(j.query?.results || {})) {
      const cats = (r.printouts?.['Категория'] || []).map((c) => String(c.fulltext || c).replace(/^Категория:/, ''));
      for (const v of r.printouts?.[prop] || []) {
        const val = String(v.fulltext ?? v).trim();
        if (val && val !== 'Нет' && val !== page) fn(page, val, kindOf(cats));
      }
    }
    const next = j['query-continue-offset'];
    if (!next) break;
    offset = next;
  }
}
for (const [prop, how] of Object.entries(PROPS)) {
  let n = 0;
  await each(prop, (page, item, k) => { n += put(item, [page, how, k]); });
  console.log(`  ${prop}: ${n}`);
  total += n;
}
for (const [prop, how] of Object.entries(INVERSE)) {
  let n = 0;
  await each(prop, (item, val) => {
    n += put(item, [val, how, 'o']);
    if (how === 'c') put(val, [item, 'v', 'o']); // the component is made into the item
  });
  console.log(`  ${prop}: ${n}`);
  total += n;
}
const file = path.join(root, 'data', 'base-sources.js');
fs.writeFileSync(file, '// Generated by tools/update-sources-wiki.mjs from the semantic data of royalquest.info — don\'t edit.\n'
  + '(function (d) { if (typeof module === \'object\' && module.exports) module.exports = d; else window.RQ_BASE_SOURCES = d; })(' + JSON.stringify(out) + ');\n');
console.log(`${total} sources for ${Object.keys(out).length} items → data/base-sources.js (${(fs.statSync(file).size / 1024).toFixed(0)} KB)`);
