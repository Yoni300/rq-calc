// Upgrade (заточка) chances from the Royal Quest Wiki page "Заточка" → data/forge.js (used by the upgrade simulator).
// Usage: node tools/update-forge-wiki.mjs [--offline]   (--offline reuses source/wiki-forge.txt)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cacheFile = path.join(root, 'source', 'wiki-forge.txt');
const outFile = path.join(root, 'data', 'forge.js');

let text;
if (process.argv.includes('--offline')) text = fs.readFileSync(cacheFile, 'utf8');
else {
  const params = new URLSearchParams({ action: 'parse', page: 'Заточка', prop: 'wikitext', format: 'json' });
  const res = await fetch(`https://royalquest.info/api.php?${params}`, { headers: { 'User-Agent': 'rq-calc forge updater' } });
  text = (await res.json()).parse.wikitext['*'];
  fs.writeFileSync(cacheFile, text);
}

// "90%" → 0.9, "<1%" → 0.005, "—" → 0
const pct = s => (/^—|^-$/.test(s) ? 0 : /^</.test(s) ? 0.005 : parseFloat(s) / 100);
const GRADES = ['C', 'B', 'A'];
const STONES = ['shard', 'black', 'white', 'red', 'purple']; // Осколок, Чёрный, Белый, Красный, Пурпурный

// each chance table: a "+N" row with 15 success chances (C, B, A × 5 stones), then a row with 15 break chances
function parseTable(title) {
  const start = text.indexOf(`==${title}==`);
  if (start < 0) throw new Error('section not found: ' + title);
  const body = text.slice(start, text.indexOf('|}', start));
  const rows = body.split(/\n\|-/).map(r => r.split(/\n[|!]/).map(c => c.replace(/^.*\|\s*/s, '').trim()).filter(c => /^(\+\d+|\d+%|<1%|—)$/.test(c)));
  const out = Object.fromEntries(GRADES.map(g => [g, Object.fromEntries(STONES.map(s => [s, []]))]));
  for (let i = 0; i < rows.length; i++) {
    const r = rows[i];
    if (!/^\+\d+$/.test(r[0] || '')) continue;
    const level = +r[0].slice(1);
    const succ = r.slice(1), brk = rows[i + 1];
    if (succ.length !== 15 || !brk || brk.length !== 15) throw new Error(`${title} +${level}: expected 15 + 15 cells, got ${succ.length} + ${brk?.length}`);
    GRADES.forEach((g, gi) => STONES.forEach((s, si) => { out[g][s][level - 1] = [pct(succ[gi * 5 + si]), pct(brk[gi * 5 + si])]; }));
  }
  for (const g of GRADES) for (const s of STONES) if (out[g][s].length !== 10 || out[g][s].includes(undefined)) throw new Error(`${title}: ${g}/${s} is missing levels`);
  return out;
}

// +11: chance by the upgrade of the item that is used up
const s11 = text.slice(text.indexOf('==Заточка предметов на +11=='));
const plus11 = [...s11.matchAll(/\|\s*(\d+)%/g)].map(m => +m[1] / 100).slice(0, 11);
if (plus11.length !== 11) throw new Error('+11 table: expected 11 chances, got ' + plus11.length);

const data = {
  source: 'royalquest.info/wiki/Заточка',
  // [success, break] for upgrading to +1 … +10; a failure that doesn't break the item lowers the upgrade by 1
  armor: parseTable('Шансы заточки одежды'),
  oneHand: parseTable('Шансы заточки одноручных видов оружия, щитов и орбов'),
  twoHand: parseTable('Шансы заточки двуручных видов оружия'),
  plus11, // index = upgrade of the sacrificed copy (0 … +10)
};
fs.writeFileSync(outFile, `// Generated by tools/update-forge-wiki.mjs from the Royal Quest Wiki — don't edit by hand.\nwindow.RQ_FORGE = ${JSON.stringify(data)};\n`);
console.log('forge chances written:', outFile);
