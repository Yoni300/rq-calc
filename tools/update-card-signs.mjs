// How many «Знаки» each card gives when exchanged (the wiki's «Знаки» property on card pages, see the wiki page
// «Обмен карт на Знаки»). → data/card-signs.js: { "Карта Воко": 190, … } for the card scanner (card-scan.js).
// Cards that are no longer available are kept: players may still have them.   Usage: node tools/update-card-signs.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { api } from './wiki-fetch.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = {};
for (let offset = 0; offset < 5000;) {
  const j = await api({ action: 'ask', query: `[[Категория:Карты]][[Знаки::+]]|?Знаки|limit=500|offset=${offset}` });
  for (const [name, r] of Object.entries(j.query?.results || {})) {
    const n = r.printouts?.['Знаки']?.[0];
    if (typeof n === 'number' && n > 0) out[name] = n;
  }
  if (j['query-continue-offset'] == null) break;
  offset = j['query-continue-offset'];
}
const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b, 'ru')));
const file = path.join(root, 'data', 'card-signs.js');
fs.writeFileSync(file, '// Generated by tools/update-card-signs.mjs from the Royal Quest Wiki (royalquest.info) — don\'t edit.\n'
  + '// Card name → «Знаки» it gives when exchanged.\n'
  + '(function (d) { if (typeof module !== \'undefined\') module.exports = d; else window.RQ_CARD_SIGNS = d; })('
  + JSON.stringify(sorted, null, 0).replace(/,"/g, ',\n"') + ');\n');
console.log(`${Object.keys(sorted).length} cards → ${path.relative(root, file)}`);
